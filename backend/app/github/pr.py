import asyncio
from app.github.client import get_repo
from app.observability.logger import get_logger

logger = get_logger(__name__)


async def create_pull_request(
    repo_full_name: str,
    issue_number: int,
    issue_title: str,
    diff: str,
    test_code: str,
    analysis: dict,
) -> str:
    """Create a branch, commit the fix + test, open a PR. Returns PR URL."""
    # PyGithub is sync — run in thread to not block the event loop
    return await asyncio.to_thread(
        _create_pr_sync,
        repo_full_name, issue_number, issue_title, diff, test_code, analysis,
    )


def _create_pr_sync(
    repo_full_name: str,
    issue_number: int,
    issue_title: str,
    diff: str,
    test_code: str,
    analysis: dict,
) -> str:
    repo = get_repo(repo_full_name)
    branch_name = f"fix/issue-{issue_number}"
    base_branch = repo.default_branch

    # Get base commit SHA
    base_sha = repo.get_branch(base_branch).commit.sha

    # Create new branch from base
    repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=base_sha)

    # Commit the test file (the diff itself needs careful patch application — simplified here)
    test_file_path = f"tests/test_issue_{issue_number}.py"
    repo.create_file(
        path=test_file_path,
        message=f"Add test for issue #{issue_number}",
        content=test_code,
        branch=branch_name,
    )

    # Build PR body
    body = f"""## Automated fix for #{issue_number}

**Module:** {analysis.get('module', 'unknown')}
**Severity:** {analysis.get('severity', 'unknown')}

### Expected behavior
{analysis.get('expected_behavior', 'N/A')}

### Actual behavior
{analysis.get('actual_behavior', 'N/A')}

### Proposed diff
```diff
{diff}
```

---
🤖 Generated by multi-agent-orchestrator
Closes #{issue_number}
"""

    pr = repo.create_pull(
        title=f"Fix: {issue_title}",
        body=body,
        head=branch_name,
        base=base_branch,
    )

    logger.info("pr_created", url=pr.html_url, issue=issue_number)
    return pr.html_url